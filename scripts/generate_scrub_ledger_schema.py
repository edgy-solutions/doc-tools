#!/usr/bin/env python
"""Project ``ScrubLedger`` into ``registry/scrub_ledger.schema.json``.

Run it from PowerShell on this repo's venv interpreter, never a bare python:

    & .\\.venv\\Scripts\\python.exe scripts\\generate_scrub_ledger_schema.py

WHY GENERATED AND NOT HAND-WRITTEN. The Pydantic models in
``doc_tools/scrub/ledger.py`` are the authority, because they are what actually
rejects a bad ledger at load. A hand-maintained JSON Schema beside them could
disagree, and the failure mode is the quiet one: a reviewer or a non-Python
consumer validating against a schema that permits what the loader refuses — or
worse, permits an original value in the clear.

So the schema is a **projection**, pinned by ``tests/test_scrub_ledger.py``
exactly as ``registry/content_kinds/`` is pinned by ``test_kind_registry.py``.

WHAT THE PROJECTION CANNOT CARRY. JSON Schema expresses the shapes and the
patterns — including ``^len=\\d+ sha256:[0-9a-f]{8}$``, which is the rule that
matters most — but not the cross-field invariants: shape equality between a
declared shape and its replacement, occurrences matching the site count, the
mapping policy agreeing with ``mapping_ref``, injectivity of the mapping, or a
replacement landing on an allowlisted string. Those live only in the model
validators. **A consumer that validates with JSON Schema alone has checked the
shape of a ledger, not its truth**, and the generated file says so in its own
``$comment``.
"""
from __future__ import annotations

import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

OUT = os.path.join(ROOT, "registry", "scrub_ledger.schema.json")

ONLY_SHAPE = (
    "GENERATED by scripts/generate_scrub_ledger_schema.py from "
    "doc_tools/scrub/ledger.py -- do not edit. This schema expresses the SHAPE "
    "of a ledger, including the redaction pattern for every original value. It "
    "does NOT express the cross-field invariants: shape equality of each "
    "replacement, occurrences == len(sites), policy.mapping agreeing with "
    "scrub.mapping_ref, injectivity of the mapping, or a replacement colliding "
    "with an allowlisted string. Those are enforced only by "
    "ScrubLedger.model_validate(). Validating against this file alone checks a "
    "ledger's shape, not its truth."
)


def build() -> dict:
    from doc_tools.scrub.ledger import LEDGER_VERSION, ScrubLedger

    schema = ScrubLedger.model_json_schema(by_alias=True)
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://edgy-solutions.com/schema/scrub_ledger_v1.json"
    schema["$comment"] = ONLY_SHAPE
    schema["title"] = f"Scrub ledger v{LEDGER_VERSION}"
    return schema


def main() -> int:
    text = json.dumps(build(), indent=2, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        current = ""
        if os.path.exists(OUT):
            with io.open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            print("SCHEMA DRIFT: regenerate with "
                  "scripts/generate_scrub_ledger_schema.py")
            return 1
        print("schema matches")
        return 0
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
